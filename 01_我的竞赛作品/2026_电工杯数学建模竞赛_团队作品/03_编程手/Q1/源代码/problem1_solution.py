"""
问题一：老人数量递推预测模型（每步取整，消除浮点累积误差）
"""
import numpy as np
import pandas as pd

# ============================================================
# 参数
# ============================================================
d      = 0.05   # 年均自然死亡率
U    = 0.07   # 年均新增比例
P_alpha = 0.045 # 自理 -> 半失能 转移概率
P_beta  = 0.10  # 半失能 -> 失能 转移概率

# ============================================================
# 附件1 数据（第0年末 = 当前状态）
# ============================================================
raw = {
    '小区':   ['A', 'B', 'C', 'D', 'E', 'F', 'G', 'H', 'I', 'J'],
    '自理':   [496, 408, 632, 368, 536, 328, 592, 392, 504, 456],
    '半失能': [152, 136, 208, 120, 176, 104, 192, 128, 168, 144],
    '失能':   [64,  64,  80,  56,  72,  40,  80,  48,  64,  56],
}

# ============================================================
# 转移矩阵 P：X(t+1) = P @ X(t)
# ============================================================
P = np.array([
    [(1-d)*(1-P_alpha)+U,  U,                   U                 ],
    [(1-d)*P_alpha,          (1-d)*(1-P_beta),      0                   ],
    [0,                      (1-d)*P_beta,          (1-d)               ],
])

print("=" * 55)
print("转移矩阵 P :")
print(np.array2string(P, precision=4, suppress_small=True))
print(f"列和: {P.sum(axis=0)}  (净增长率 = {((1-d+U)-1)*100:+.1f}%/年)")

# ============================================================
# 5年递推（每步取整）
# ============================================================
years = 5
print(f"\n{'='*55}")
print("各小区逐年预测（每步取整后递推）")
print(f"{'='*55}")

# 存储所有结果
all_tables = {}   # all_tables[year] = list of rows

for _, r in pd.DataFrame(raw).iterrows():
    name = r['小区']
    a0, b0, c0 = int(r['自理']), int(r['半失能']), int(r['失能'])
    N_int = np.array([a0, b0, c0], dtype=int)
    print(f"\n小区 {name}  初始: 自理={a0}  半失能={b0}  失能={c0}  总数={N_int.sum()}")

    for t in range(years + 1):
        row = {
            '小区': name, '年份': f'第{t}年末',
            '自理': N_int[0], '半失能': N_int[1],
            '失能': N_int[2], '总数': N_int.sum()
        }
        if t not in all_tables:
            all_tables[t] = []
        all_tables[t].append(row)

        if t == years:
            break

        # 用取整后的值做下一步递推
        N_float = P @ N_int.astype(float)
        N_int = np.array([round(N_float[0]), round(N_float[1]), round(N_float[2])], dtype=int)

# ============================================================
# 逐年输出表格
# ============================================================
for t in range(years + 1):
    print(f"\n--- 第{t}年末 ---")
    print(f"{'小区':>4} {'自理':>6} {'半失能':>6} {'失能':>6} {'总数':>6}")
    for row in all_tables[t]:
        print(f"{row['小区']:>4} {row['自理']:>6} {row['半失能']:>6} {row['失能']:>6} {row['总数']:>6}")

# ============================================================
# 导出 Excel
# ============================================================
rows_export = []
for t in range(years + 1):
    rows_export.extend(all_tables[t])

df = pd.DataFrame(rows_export)
output_path = r'c:\Users\29845\Desktop\电工杯\预测结果_取整.xlsx'
df.to_excel(output_path, index=False)
print(f"\n结果已导出至: {output_path}")
